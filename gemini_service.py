import base64
import requests
import json
import logging
from config import Config

logger = logging.getLogger(__name__)

class GeminiService:
    BASE_URL = "https://generativelanguage.googleapis.com/v1beta"
    
    @classmethod
    def get_api_key(cls):
        return Config.GEMINI_API_KEY

    @classmethod
    def generate_content(cls, contents, system_instruction=None, temperature=0.3):
        """
        Generic content generator calling Gemini API.
        contents can be a list of parts or structured dict.
        """
        key = cls.get_api_key()
        if not key:
            raise ValueError("GEMINI_API_KEY is not configured in .env")
            
        url = f"{cls.BASE_URL}/models/{Config.GEMINI_MODEL}:generateContent?key={key}"
        
        payload = {
            "contents": contents if isinstance(contents, list) else [contents],
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": 2048,
            }
        }
        
        if system_instruction:
            payload["systemInstruction"] = {
                "parts": [{"text": system_instruction}]
            }
            
        headers = {"Content-Type": "application/json"}
        try:
            response = requests.post(url, json=payload, headers=headers, timeout=30)
            if response.status_code == 200:
                data = response.json()
                candidates = data.get("candidates", [])
                if candidates and "content" in candidates[0]:
                    parts = candidates[0]["content"].get("parts", [])
                    return "".join(p.get("text", "") for p in parts)
                return "No recommendation generated by Gemini API."
            else:
                logger.error(f"Gemini API error ({response.status_code}): {response.text}")
                return f"Gemini API returned an error: {response.text[:200]}"
        except Exception as e:
            logger.exception("Gemini API call exception")
            return f"Error communicating with Gemini AI: {str(e)}"

    @classmethod
    def get_embedding(cls, text):
        """
        Generate embedding vector using gemini-embedding-001
        """
        key = cls.get_api_key()
        if not key:
            return None
            
        url = f"{cls.BASE_URL}/models/{Config.GEMINI_EMBEDDING_MODEL}:embedContent?key={key}"
        payload = {
            "content": {"parts": [{"text": text[:2000]}]}
        }
        headers = {"Content-Type": "application/json"}
        
        try:
            response = requests.post(url, json=payload, headers=headers, timeout=20)
            if response.status_code == 200:
                return response.json().get("embedding", {}).get("values", [])
            else:
                logger.warning(f"Embedding API failed ({response.status_code}): {response.text[:150]}")
                return None
        except Exception as e:
            logger.warning(f"Embedding error: {e}")
            return None

    @classmethod
    def analyze_image_and_extract_symptoms(cls, image_bytes, mime_type="image/jpeg", user_prompt=""):
        """
        Multimodal analysis: inspects user-provided image (e.g. skin rash, herb, tongue, thermometer, report)
        and extracts clinical observations, symptoms, and condition keywords.
        """
        b64_data = base64.b64encode(image_bytes).decode("utf-8")
        
        prompt = (
            "You are an expert Ayurvedic diagnostic assistant. Inspect this user-uploaded health image "
            "(which may show a skin symptom, tongue, eye condition, medicinal herb, thermometer reading, or medical report). "
            f"User note: '{user_prompt}'.\n\n"
            "Provide a concise analysis in JSON format with exactly these keys:\n"
            "{\n"
            "  \"image_type\": \"(e.g., skin rash / tongue coating / medicinal herb / lab report / other)\",\n"
            "  \"visual_observations\": \"(detailed visual findings)\",\n"
            "  \"detected_symptoms\": [\"list\", \"of\", \"symptoms\"],\n"
            "  \"likely_ayurvedic_condition\": \"(e.g. Twak Roga, Pitta aggravation, Jwara, Kasa)\",\n"
            "  \"search_query\": \"(a clear search query to retrieve relevant Ayurvedic remedies)\"\n"
            "}\n"
            "Output ONLY valid JSON."
        )
        
        contents = [{
            "parts": [
                {"text": prompt},
                {
                    "inline_data": {
                        "mime_type": mime_type,
                        "data": b64_data
                    }
                }
            ]
        }]
        
        raw_result = cls.generate_content(contents, temperature=0.1)
        # Parse JSON
        try:
            clean_json = raw_result.strip()
            if clean_json.startswith("```json"):
                clean_json = clean_json[7:]
            if clean_json.endswith("```"):
                clean_json = clean_json[:-3]
            clean_json = clean_json.strip()
            return json.loads(clean_json)
        except Exception:
            return {
                "image_type": "Health symptom or herb image",
                "visual_observations": raw_result,
                "detected_symptoms": [user_prompt or "Visual symptom observed"],
                "likely_ayurvedic_condition": "Health Imbalance",
                "search_query": user_prompt or "Ayurvedic natural cure"
            }

    @classmethod
    def generate_rag_remedy(cls, user_prompt, retrieved_docs, preferred_language="English", image_analysis=None, doctor_insights=None):
        """
        Generate step-by-step Ayurvedic suggestion grounded in retrieved RAG knowledge and doctor notes,
        strictly delivered in the user's preferred language.
        """
        system_instruction = (
            "You are 'AyurCare Copilot', an empathetic, authentic, and certified Ayurvedic AI Healthcare Assistant.\n"
            "Your mission is to provide structured, safe, step-by-step natural curing techniques based on classical Ayurveda "
            "(Charaka Samhita, Sushruta Samhita, Ashtanga Hridaya) and validated holistic practices.\n\n"
            f"CRITICAL REQUIREMENT: Deliver your ENTIRE final response in the user's chosen language: '{preferred_language}'. "
            "Translate all section titles, remedy steps, dietary advice, and warnings into that language naturally, fluently, and respectfully. "
            "If the language is Hindi, Telugu, Tamil, Marathi, Bengali, Kannada, Gujarati, Spanish, French, etc., use their proper native script.\n\n"
            "Structure your response with clear Markdown headings:\n"
            "1. 🌿 Condition Overview & Dosha Analysis (Vata, Pitta, Kapha balance)\n"
            "2. 📋 Step-by-Step Natural Curing Techniques (Step 1, Step 2, Step 3 with precise preparation, ingredients, dosage, and timing)\n"
            "3. 🥗 Pathya & Apathya Diet (Healing foods to consume vs. foods strictly to avoid)\n"
            "4. 🧘 Yoga, Pranayama & Lifestyle Practices\n"
            "5. ⚠️ Emergency Red-Flag Warnings (Clear medical criteria for when the user MUST seek immediate hospital / emergency care)\n\n"
            "Tone: Warm, authoritative yet gentle, reassuring. Always emphasize that natural remedies complement medical safety."
        )
        
        context_text = "### GROUNDED AYURVEDIC KNOWLEDGE (RAG RETRIEVAL):\n"
        for idx, doc in enumerate(retrieved_docs, 1):
            context_text += f"\n--- Source Document {idx}: {doc.get('condition_name', 'Remedy')} ---\n"
            context_text += f"Ayurvedic Name: {doc.get('ayurvedic_name', '')}\n"
            context_text += f"Dosha: {doc.get('dosha_involved', doc.get('dosha_type', ''))}\n"
            context_text += f"Symptoms: {doc.get('common_symptoms', doc.get('symptoms', ''))}\n"
            context_text += f"Remedies: {doc.get('step_by_step_remedy', doc.get('step_by_step_cure', ''))}\n"
            context_text += f"Herbs: {doc.get('herbs_and_ingredients', doc.get('herbs_used', ''))}\n"
            context_text += f"Diet (Pathya): {doc.get('pathya_diet_recommended', doc.get('dietary_guidelines', ''))}\n"
            context_text += f"Avoid (Apathya): {doc.get('apathya_diet_avoid', doc.get('contraindications', ''))}\n"
            if doc.get('emergency_escalation_triggers'):
                context_text += f"Emergency Triggers: {doc.get('emergency_escalation_triggers')}\n"
                
        if doctor_insights:
            context_text += "\n### REGISTERED DOCTOR & CLINICAL CONTRIBUTIONS:\n"
            for d in doctor_insights:
                context_text += f"Doctor {d.get('doctor_name', 'Doctor')} ({d.get('doctor_specialization', 'Physician')}): {d.get('step_by_step_cure', '')}\n"

        prompt_parts = []
        if image_analysis:
            prompt_parts.append(f"Visual Image Findings:\n{json.dumps(image_analysis, indent=2)}\n")
            
        prompt_parts.append(f"User Health Condition / Symptom Prompt: '{user_prompt}'\n")
        prompt_parts.append(f"User Preferred Language: '{preferred_language}'\n\n")
        prompt_parts.append(context_text)
        prompt_parts.append(
            f"\nPlease analyze the above condition thoroughly and generate the step-by-step Ayurvedic suggestions completely in {preferred_language}."
        )
        
        contents = [{"parts": [{"text": "\n".join(prompt_parts)}]}]
        return cls.generate_content(contents, system_instruction=system_instruction, temperature=0.3)
